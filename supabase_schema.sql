-- Function to let admin create a new auth user securely
CREATE OR REPLACE FUNCTION public.admin_create_user(
  p_email TEXT,
  p_password TEXT,
  p_username TEXT,
  p_role TEXT
)
RETURNS UUID
SECURITY DEFINER
SET search_path = public, auth, extensions
AS $$
DECLARE
  v_user_id UUID;
  v_caller_role TEXT;
BEGIN
  -- Verify the caller is an admin
  SELECT role INTO v_caller_role FROM public.profiles WHERE id = auth.uid();
  IF v_caller_role IS DISTINCT FROM 'admin' THEN
    RAISE EXCEPTION 'Access Denied: Only administrators can create users.';
  END IF;

  v_user_id := gen_random_uuid();

  -- Insert into auth.users (authentication credentials)
  INSERT INTO auth.users (
    id,
    instance_id,
    email,
    encrypted_password,
    email_confirmed_at,
    raw_app_meta_data,
    raw_user_meta_data,
    aud,
    role,
    created_at,
    updated_at,
    confirmation_token,
    email_change_token_new,
    email_change,
    recovery_token,
    phone
  )
  VALUES (
    v_user_id,
    '00000000-0000-0000-0000-000000000000',
    p_email,
    crypt(p_password, gen_salt('bf', 10)),
    now(),
    '{"provider":"email","providers":["email"]}'::jsonb,
    jsonb_build_object(
      'sub', v_user_id::text,
      'email', p_email,
      'username', p_username,
      'email_verified', true,
      'phone_verified', false
    ),
    'authenticated',
    'authenticated',
    now(),
    now(),
    '',
    '',
    '',
    '',
    NULL
  );

  -- Insert into auth.identities to link email provider identity
  INSERT INTO auth.identities (
    id,
    user_id,
    identity_data,
    provider,
    provider_id,
    last_sign_in_at,
    created_at,
    updated_at
  )
  VALUES (
    v_user_id,
    v_user_id,
    jsonb_build_object(
      'sub', v_user_id::text,
      'email', p_email,
      'username', p_username,
      'email_verified', false,
      'phone_verified', false
    ),
    'email',
    v_user_id::text,
    now(),
    now(),
    now()
  );

  -- Explicitly create the profiles row (to map username, role, and set pending status)
  INSERT INTO public.profiles (id, employee_id, email, username, role, status, last_seen_at)
  VALUES (
    v_user_id, 
    'EMP-' || substring(v_user_id::text from 1 for 4), 
    p_email,
    p_username, 
    p_role, 
    'pending',
    now()
  )
  ON CONFLICT (id) DO UPDATE
  SET email = p_email, role = p_role, username = p_username, status = 'pending';

  RETURN v_user_id;
END;
$$ LANGUAGE plpgsql;

-- Function to let admin reset any user password securely
CREATE OR REPLACE FUNCTION public.admin_reset_password(
  p_user_id UUID,
  p_new_password TEXT
)
RETURNS VOID
SECURITY DEFINER
SET search_path = public, auth, extensions
AS $$
DECLARE
  v_caller_role TEXT;
BEGIN
  -- Verify the caller is an admin
  SELECT role INTO v_caller_role FROM public.profiles WHERE id = auth.uid();
  IF v_caller_role IS DISTINCT FROM 'admin' THEN
    RAISE EXCEPTION 'Access Denied: Only administrators can reset passwords.';
  END IF;

  -- Update auth.users password
  UPDATE auth.users
  SET encrypted_password = crypt(p_new_password, gen_salt('bf', 10)),
      updated_at = now()
  WHERE id = p_user_id;

  -- Force user status back to pending so they must change it upon next login
  UPDATE public.profiles
  SET status = 'pending'
  WHERE id = p_user_id;
END;
$$ LANGUAGE plpgsql;

-- Function to let admin delete any user securely
CREATE OR REPLACE FUNCTION public.admin_delete_user(
  p_user_id UUID
)
RETURNS VOID
SECURITY DEFINER
SET search_path = public, auth, extensions
AS $$
DECLARE
  v_caller_role TEXT;
BEGIN
  -- Verify the caller is an admin
  SELECT role INTO v_caller_role FROM public.profiles WHERE id = auth.uid();
  IF v_caller_role IS DISTINCT FROM 'admin' THEN
    RAISE EXCEPTION 'Access Denied: Only administrators can delete users.';
  END IF;

  -- Delete from profiles first to bypass foreign key constraint violations
  DELETE FROM public.profiles WHERE id = p_user_id;

  -- Delete from auth.users (authentication credentials)
  DELETE FROM auth.users WHERE id = p_user_id;
END;
$$ LANGUAGE plpgsql;
